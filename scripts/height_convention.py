# -*- coding: utf-8 -*-
"""Y 轴高度约定：常数推导 + 验算。

老板定的规则
------------
* 原版数据（def 的 size/drawSize）一律不作数。
* **唯一参考 = 角色贴图的世界长宽** + 现实家具尺寸 + 现实人类身高。
* 原版没有高度轴，全部由我们自行约定魔法常数。

推导
----
RimWorld 里 Pawn 恒占1x1 格（世界规则，非 def 数据）。
Pawn 贴图128px铺满这1 格 => **128 px == 1 格**。

现实参照：
    成人身高 1.75 m，肩宽 0.45 m。
    标准床1.0 m x 2.0 m。

两个独立锚点必须给出同一个答案，否则约定不成立：
  锚点 A（人）：1 格宽要装下肩宽 0.45 m 的人 -> 1 格 >= 0.45 m
  锚点 B（床）：RimWorld 的床是 1x2 格 -> 对应现实 1.0 m x 2.0 m
                -> 1 格 = 1.0 m
  两者相容（1 格 = 1 m 时，肩宽 0.45 m 占 45% 格宽，符合"人站格中央"）。

=> 约定 **1 格 = 1.00 米**，X / Y / Z 三轴同构，无需任何缩放。
"""

# ===== 唯一魔法常数 =====
METERS_PER_CELL = 1.00


def h(meters: float) -> float:
    """现实米 -> 格（Y 轴高度）。"""
    return meters / METERS_PER_CELL


# ===== 现实尺寸基准表（单位：米）=====
