if __name__ == "__main__":
    print("=" * 66)
    print(f"Y 轴高度约定：1 格 = {METERS_PER_CELL:.2f} 米（三轴同构）")
    print("=" * 66)
    print(f"{'项目':<14}{'现实(米)':>10}{'Y轴(格)':>10}")
    print("-" * 36)
    for k, v in REAL.items():
        print(f"{k:<14}{v:>10.2f}{h(v):>10.2f}")
    print("-" * 36)
    print()
    print("锚点自洽性检查：")
    print(f"  成人肩宽 0.45 m 占1 格宽的 {0.45/METERS_PER_CELL*100:.0f}%  -> 人站格中央，余量充足")
